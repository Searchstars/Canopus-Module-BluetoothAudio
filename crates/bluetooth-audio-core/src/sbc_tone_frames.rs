pub const fn frame_length(bitpool: u8) -> Option<usize> {
    if bitpool < MIN_BITPOOL || bitpool > MAX_BITPOOL {
        return None;
    }
    Some(12 + 2 * bitpool as usize)
}

pub fn write_frame(bitpool: u8, out: &mut [u8]) -> Option<usize> {
    let length = frame_length(bitpool)?;
    if out.len() < length {
        return None;
    }
    let n = (bitpool - MIN_BITPOOL) as usize;
    let offset = n * (bitpool as usize + 38);
    let encoded = ENCODED_FRAMES.get(offset..offset + length)?;
    for (destination, source) in out[..length].iter_mut().zip(encoded) {
        *destination = *source ^ XOR_MASK;
    }
    Some(length)
}
